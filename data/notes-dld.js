"## 2.6 Flip-flops",
"",
"A **flip-flop** is a 1-bit memory element — a bistable circuit that holds its state until told to change. It is the building block of all sequential circuits.",
"",
"### S-R flip-flop",
"",
"| S | R | $Q_{n+1}$ | Remark |",
"|---|---|---|---|",
"| 0 | 0 | $Q_n$ | No change |",
"| 0 | 1 | 0 | Reset |",
"| 1 | 0 | 1 | Set |",
"| 1 | 1 | — | **Invalid** |",
"",
"$$Q_{n+1} = S + \\bar R Q_n, \\quad \\text{with } SR = 0$$",
"",
"**Drawback:** the $S=R=1$ state is undefined — both outputs go to the same level, and the final state is unpredictable when the inputs return to 0.",
"",
"### J-K flip-flop",
"",
"Removes the invalid state by feeding the outputs back: $S = J\\bar Q_n$, $R = KQ_n$.",
"",
"| J | K | $Q_{n+1}$ | Remark |",
"|---|---|---|---|",
"| 0 | 0 | $Q_n$ | No change |",
"| 0 | 1 | 0 | Reset |",
"| 1 | 0 | 1 | Set |",
"| 1 | 1 | $\\bar Q_n$ | **Toggle** |",
"",
"$$\\boxed{Q_{n+1} = J\\bar Q_n + \\bar K Q_n}$$",
"",
"### Race around condition",
"",
"**The problem.** When $J = K = 1$ and the clock pulse width $t_p$ is **greater than** the propagation delay $\\Delta t$, the output toggles, is fed straight back, and toggles again — repeatedly for the whole duration of the clock pulse. The final state when the clock goes low is **indeterminate**.",
"",
"$$\\text{Race around occurs when } t_p > \\Delta t$$",
"",
"**Remedies:**",
"1. **Make $t_p < \\Delta t$** — a very narrow clock pulse. Impractical and unreliable.",
"2. **Master–Slave configuration** *(the standard solution)* — two J-K flip-flops in cascade. The **master** is enabled when the clock is HIGH, the **slave** when it is LOW (inverted clock). Data enters the master on the rising edge but reaches the output only on the falling edge, so the output cannot change while the master is being loaded. **Only one toggle per clock cycle.**",
"3. **Edge triggering** — respond only to the clock *edge*, which is effectively zero width.",
"",
"### D and T flip-flops",
"",
"$$D: \\;Q_{n+1} = D \\qquad\\qquad T: \\;Q_{n+1} = T \\oplus Q_n$$",
"",
"The D flip-flop delays its input by one clock period — used in registers. The T flip-flop toggles — used in counters.",
