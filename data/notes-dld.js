"For high-speed block transfers (disk, network), even interrupt-driven I/O is too slow. A **DMA controller** takes over the buses and moves a whole block directly between device and memory.",
"",
"| Register | Contents |",
"|---|---|",
"| **Address register** | Memory address for the next word |",
"| **Word count register** | Number of words remaining |",
"| **Control register** | Direction, mode, enable |",
"| **Status register** | Done, error flags |",
"",
"### Sequence of a DMA transfer",
"",
"1. The CPU programs the controller: starting address, word count, direction. It then continues other work",
"2. When the device is ready, the controller asserts **BR (Bus Request / HOLD)**",
"3. The CPU completes the current bus cycle, floats its bus drivers and replies with **BG (Bus Grant / HLDA)**",
"4. The controller owns the buses and transfers data **directly** between device and memory, incrementing the address and decrementing the count",
"5. When the count reaches zero it releases the buses and raises an **interrupt** to signal completion",
"",
"```",
"          ┌──────┐   BR  ┌──────────────┐",
"          │ CPU  │◀──────┤     DMA      │◀──── device request",
"          │      ├──────▶│  controller  │",
"          └──┬───┘   BG  └──────┬───────┘",
"  ═══════════╪══════════════════╪═════════ address / data / control bus",
"        ┌────▼────┐        ┌────▼─────┐",
"        │ Memory  │        │ I/O dev  │",
"        └─────────┘        └──────────┘",
"```",
"",
"### Transfer modes",
"",
"| Mode | Description | CPU impact |",
"|---|---|---|",
"| **Burst (block)** | Whole block in one go | CPU stalled throughout — fastest transfer |",
"| **Cycle stealing** | One word per bus acquisition | CPU slowed only slightly |",
"| **Transparent** | Only in cycles the CPU does not need the bus | No CPU slowdown, but slowest |",
"",
"A **two-channel DMA controller** contains two independent sets of address/count/control registers with a priority arbiter, so two devices can have transfers in progress simultaneously.",
