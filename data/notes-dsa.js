"#define MAX 5",
"int q[MAX], front = -1, rear = -1;",
"",
"void enqueue(int x) {",
"    if (rear == MAX - 1) { printf(\"Queue Overflow\\n\"); return; }",
"    if (front == -1) front = 0;",
"    q[++rear] = x;",
