"## 5.9 Hashing",
"",
"Searching an array is $O(n)$ and a balanced tree $O(\\log n)$. **Hashing** achieves **average $O(1)$** by computing the storage location directly from the key:",
"",
"$$\\text{index} = h(\\text{key})$$",
"",
"### Hash functions",
"",
"| Method | Formula |",
"|---|---|",
"| **Division** | $h(k) = k \\bmod m$, with $m$ **prime** |",
"| **Mid-square** | Square the key, take the middle digits |",
"| **Folding** | Split the key into parts and add |",
"| **Multiplication** | $h(k) = \\lfloor m(kA \\bmod 1)\\rfloor$ |",
"",
"### Properties of a good hash function",
"",
"1. **Fast to compute** — $O(1)$, otherwise the advantage is lost",
"2. **Uniform distribution** — every slot equally likely",
"3. **Minimises collisions**",
"4. **Uses the entire key** — ignoring part of it clusters similar keys",
"5. **Deterministic** — same key always gives the same index",
"6. **Avalanche effect** — a small change in the key changes the index substantially",
"7. **Range-bounded** — output always within the table",
"",
"### Collisions",
"",
"A **collision** occurs when two keys hash to the same index. By the pigeonhole principle these are unavoidable.",
"",
"**Load factor** $\\alpha = n/m$. Performance degrades sharply as $\\alpha \\to 1$; tables are usually resized above $\\alpha = 0.7$.",
"",
"### Collision handling",
"",
"**A. Open addressing** — all elements live inside the table; probe for a free slot.",
"",
"| Technique | Probe sequence | Problem |",
"|---|---|---|",
"| **Linear probing** | $h(k)+1, h(k)+2, \\ldots \\pmod m$ | **Primary clustering** — long runs form |",
"| **Quadratic probing** | $h(k)+1^2, h(k)+2^2, \\ldots$ | Secondary clustering; may miss free slots |",
"| **Double hashing** | $h_1(k) + i\\,h_2(k)$ | Best distribution, slightly slower |",
"",
"**B. Separate chaining** — each slot holds a **linked list** of colliding keys.",
"*Merits:* simple; table never overflows; easy deletion; tolerates $\\alpha > 1$.",
"*Demerits:* pointer memory; poor cache locality; worst case $O(n)$.",
"",
"| Operation | Average | Worst |",
"|---|---|---|",
"| Search / Insert / Delete | $O(1)$ | $O(n)$ |",
"",
"**Applications:** compiler symbol tables, database indexing, caches, `HashMap`/`HashSet`/Python `dict`, password storage, duplicate detection, file integrity checksums.",
"",
