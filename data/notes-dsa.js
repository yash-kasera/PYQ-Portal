"",
"The array is treated as a ring using modulo arithmetic.",
"",
"```c",
"int isFull(void)  { return front == (rear + 1) % MAX; }",
"int isEmpty(void) { return front == -1; }",
"",
"void enqueue(int x) {",
"    if (isFull()) { printf(\"Queue is Full\\n\"); return; }",
"    if (front == -1) front = 0;",
"    rear = (rear + 1) % MAX;        /* wrap around */",
"    q[rear] = x;",
"}",
"int dequeue(void) {",
"    if (isEmpty()) { printf(\"Queue is Empty\\n\"); return -1; }",
"    int x = q[front];",
"    if (front == rear) front = rear = -1;   /* last element removed */",
"    else front = (front + 1) % MAX;",
"    return x;",
"}",
"```",
