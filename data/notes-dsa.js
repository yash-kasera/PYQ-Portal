"## 5.7 Heap sort",
"",
"A **heap** is a complete binary tree stored in an array satisfying the heap property: in a **max heap** every parent is $\\ge$ its children; in a **min heap** every parent is $\\le$ its children.",
"",
"```c",
"void heapify(int a[], int n, int i) {",
"    int largest = i, l = 2*i + 1, r = 2*i + 2;",
"    if (l < n && a[l] > a[largest]) largest = l;",
"    if (r < n && a[r] > a[largest]) largest = r;",
"    if (largest != i) {",
"        int t = a[i]; a[i] = a[largest]; a[largest] = t;",
"        heapify(a, n, largest);",
"    }",
"}",
"",
"void heapSort(int a[], int n) {",
"    for (int i = n/2 - 1; i >= 0; i--) heapify(a, n, i);   /* build heap: O(n) */",
"    for (int i = n - 1; i > 0; i--) {",
"        int t = a[0]; a[0] = a[i]; a[i] = t;               /* max to the end   */",
"        heapify(a, i, 0);                                   /* O(log n) each   */",
"    }",
"}",
"```",
"",
"$O(n\\log n)$ in all cases, $O(1)$ space, **not stable**.",
"",
"> **To sort in DECREASING order, build a MIN heap** instead of a max heap. Each extracted minimum goes to the end, leaving the array in descending order. This catches many students out.",
"",
