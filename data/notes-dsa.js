"    int n1 = m - l + 1, n2 = r - m;",
"    int L[n1], R[n2];",
"    for (int i = 0; i < n1; i++) L[i] = a[l + i];",
"    for (int j = 0; j < n2; j++) R[j] = a[m + 1 + j];",
"    int i = 0, j = 0, k = l;",
"    while (i < n1 && j < n2) a[k++] = (L[i] <= R[j]) ? L[i++] : R[j++];",
"    while (i < n1) a[k++] = L[i++];",
"    while (j < n2) a[k++] = R[j++];",
"}",
"",
"void mergeSort(int a[], int l, int r) {",
"    if (l < r) {",
"        int m = l + (r - l) / 2;",
"        mergeSort(a, l, m);",
"        mergeSort(a, m + 1, r);",
"        merge(a, l, m, r);",
"    }",
"}",
"```",
"",
"$O(n\\log n)$ in **all three cases** — best, average and worst. **Stable.** Its only drawback is the $O(n)$ auxiliary array, which is why it is not in-place. Preferred for **linked lists** (where no extra space is needed) and for **external sorting** of files too large for memory.",
