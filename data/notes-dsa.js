"## 5.10 Graphs",
"",
"A **graph** $G = (V,E)$ consists of a set of **vertices** and a set of **edges** joining pairs of them.",
"",
"| Term | Meaning |",
"|---|---|",
"| **Directed (digraph)** | Edges have direction; $(u,v) \\ne (v,u)$ |",
"| **Undirected** | Edges have no direction |",
"| **Weighted** | Each edge carries a cost |",
"| **Degree** | Number of incident edges; in-degree and out-degree for digraphs |",
"| **Path** | Sequence of vertices joined by edges |",
"| **Cycle** | A path starting and ending at the same vertex |",
"| **Connected** | A path exists between every pair |",
"| **Complete** | Every pair joined; $n(n-1)/2$ edges |",
"| **DAG** | Directed acyclic graph |",
"",
"### Representations",
"",
"**Adjacency matrix** — $V\\times V$; $A[i][j] = 1$ (or the weight) if an edge exists.",
"**Adjacency list** — an array of $V$ linked lists of neighbours.",
"",
"| | Adjacency matrix | Adjacency list |",
"|---|---|---|",
"| Space | $O(V^2)$ | **$O(V+E)$** |",
"| Edge lookup | **$O(1)$** | $O(\\deg v)$ |",
"| List neighbours | $O(V)$ | **$O(\\deg v)$** |",
"| Add a vertex | Expensive | Easy |",
"| Best for | **Dense** graphs | **Sparse** graphs (most real graphs) |",
"",
"### Traversal algorithms",
"",
"**Breadth-First Search** — explores all neighbours at the current depth before going deeper. Uses a **queue**.",
"```c",
"void BFS(struct Graph *g, int start) {",
"    int visited[MAX] = {0}, queue[MAX], front = 0, rear = 0;",
"    visited[start] = 1;  queue[rear++] = start;",
"    while (front < rear) {",
"        int v = queue[front++];",
"        printf(\"%d \", v);",
"        for (struct AdjNode *p = g->array[v]; p; p = p->next)",
"            if (!visited[p->dest]) { visited[p->dest] = 1; queue[rear++] = p->dest; }",
"    }",
"}",
"```",
"",
"**Depth-First Search** — goes as deep as possible before backtracking. Uses a **stack** (or recursion).",
"```c",
"void DFS(struct Graph *g, int v, int visited[]) {",
"    visited[v] = 1;",
"    printf(\"%d \", v);",
"    for (struct AdjNode *p = g->array[v]; p; p = p->next)",
"        if (!visited[p->dest]) DFS(g, p->dest, visited);",
"}",
"```",
"",
"| | **BFS** | **DFS** |",
"|---|---|---|",
"| Data structure | **Queue** | **Stack** / recursion |",
"| Order | Level by level | Branch by branch |",
"| Time | $O(V+E)$ | $O(V+E)$ |",
"| Space | $O(V)$ | $O(V)$ |",
"| Shortest path (unweighted) | **Yes** | No |",
"| Best for | Shortest path, level order | Cycle detection, topological sort, connected components, maze solving |",
"",
"**Applications of graphs:** social networks; road maps and shortest-path routing (Dijkstra, Bellman-Ford); computer networks; dependency resolution and task scheduling (topological sort); web page ranking; circuit design; recommendation systems; AI state-space search.",
"",
