"",
"**Effects of oil spills:** a floating oil film blocks sunlight and oxygen exchange, killing plankton; birds' feathers lose insulation and buoyancy so they die of hypothermia or drowning; marine mammals are poisoned; coral reefs and mangroves are smothered; fisheries and tourism collapse; and the toxic hydrocarbons persist in sediments for decades.",
"",
"**Control:** booms to contain, skimmers to recover, sorbents to absorb, dispersants to break up (themselves toxic), controlled burning, and **bioremediation** using oil-degrading bacteria.",
"",
"#### Ganga Action Plan (1985)",
"",
"India's first major river-cleaning programme, launched to reduce pollution of the Ganga, which receives sewage from over 100 towns plus tannery, distillery and paper-mill effluent, along with idol immersion and cremation waste. GAP-I and GAP-II built interception and diversion works, sewage treatment plants, electric crematoria and low-cost sanitation. Results were limited because treatment capacity fell far short of the sewage generated and maintenance was poor. It was succeeded by the **National Ganga River Basin Authority (2009)** and the **Namami Gange Programme (2014)**."
