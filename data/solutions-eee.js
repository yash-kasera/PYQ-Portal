"### Pollution case studies",
"",
"#### Bhopal Gas Disaster (2–3 December 1984)",
"",
"**What happened.** At the Union Carbide India Limited pesticide plant in Bhopal, water entered a storage tank (E610) containing about 42 tonnes of **methyl isocyanate (MIC)**. The resulting exothermic runaway reaction raised the temperature and pressure until the safety valve gave way, releasing roughly **40 tonnes of MIC** and other toxic gases into the air over the sleeping city.",
"",
"**Why it was so severe.** Nearly every safety system had been shut down or was non-functional to cut costs — the refrigeration unit that kept MIC cold was off, the vent gas scrubber was on standby, the flare tower was under repair, and staffing and training had been reduced. Densely populated slums stood immediately next to the plant, and no community warning or evacuation plan existed.",
"",
"**Effects.** Around 3,800 people died immediately by official count, with estimates of eventual deaths from 15,000 to 25,000. Over **500,000 people were exposed**. Survivors suffer permanently from blindness and eye damage, respiratory disease, neurological disorders, reproductive problems and birth defects that continue into later generations. The site remains contaminated, and chemicals have leached into the groundwater.",
"",
"**Lessons.** It is the world's worst industrial disaster. It led directly to India's **Environment (Protection) Act 1986**, the **Public Liability Insurance Act 1991**, the Factories Act amendments, hazardous-waste rules, mandatory on-site and off-site emergency plans, and the principles of **absolute liability** and the **polluter pays**.",
"",
"#### London Smog Disaster (5–9 December 1952)",
"",
"**What happened.** An **anticyclone** settled over London, producing windless conditions and a strong **temperature inversion** that trapped air near the ground. Cold weather had increased the burning of cheap, high-sulphur domestic coal. Smoke and SO₂ from millions of chimneys, power stations and vehicles accumulated for five days, forming a dense yellow-black smog in which visibility fell to a few metres.",
"",
"**Chemistry.** SO₂ oxidised on the surface of fog droplets and soot particles to sulphuric acid aerosol — a classic **reducing (sulphurous) smog**.",
"",
"**Effects.** About **4,000 people died** during the episode and an estimated 8,000–12,000 in the following weeks, mostly from bronchitis, pneumonia and heart failure; 100,000 fell ill. Transport stopped and cattle at Smithfield market died.",
"",
"**Outcome.** It produced the UK **Clean Air Act 1956**, which established smokeless zones, required the use of smokeless fuel, moved power stations out of cities and mandated tall chimneys. It is the event that established air pollution as a lethal public-health issue.",
"",
"#### Minamata Tragedy (Japan, 1950s–60s)",
"",
"**What happened.** The Chisso Corporation's chemical factory at Minamata discharged effluent containing **methylmercury** into Minamata Bay for decades. Mercury was **biomagnified** through the food chain — plankton to small fish to large fish — reaching concentrations in fish hundreds of thousands of times that in the water. The local fishing community ate this fish daily.",
"",
"**Effects.** **Minamata disease** is a neurological syndrome caused by methylmercury attacking the central nervous system: numbness of hands and feet, loss of coordination (ataxia), slurred speech, constriction of the visual field, deafness, tremors, paralysis, insanity and death. Methylmercury crosses the placenta, so children were born with **congenital Minamata disease** — severe cerebral palsy and mental retardation — even to mothers who showed no symptoms. Cats in the town went into convulsions, and birds fell from the sky.",
"",
"Officially over 2,265 victims were certified and nearly 1,800 died; the true number affected is far higher.",
"",
"**Significance.** It is the definitive demonstration of **bioaccumulation and biomagnification**, and it led to the **Minamata Convention on Mercury (2013)**, a global treaty restricting mercury use and emissions.",
"",
"#### Major oil spills of the 20th and 21st centuries",
"",
"| Spill | Year | Detail |",
"|---|---|---|",
"| **Exxon Valdez** | 1989 | Tanker grounded in Prince William Sound, Alaska; ~37,000 tonnes; devastated sea otters, seals and seabirds |",
"| **Gulf War oil spill** | 1991 | Deliberate release into the Persian Gulf; the largest ever, ~1.5 million tonnes |",
