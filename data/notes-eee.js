"## 5.8 Protective coatings",
"",
"### Anodic versus cathodic coatings — the key distinction",
"",
"**Anodic coating** — the coating metal is **more active** than the base (zinc on iron). Even if scratched, the exposed base metal is **cathodically protected** by the surrounding coating, which sacrifices itself. **Protection continues despite damage.**",
"",
"**Cathodic (noble) coating** — the coating metal is **less active** than the base (tin on iron). It protects only while **continuous and unbroken**. If scratched, a galvanic cell forms with a **small anode (exposed iron) and a large cathode (tin)**, so the iron corrodes **more rapidly than with no coating at all**. This is why a scratched tin can rusts through so quickly.",
"",
"### Hot dipping",
"",
"The base metal is immersed in a **bath of molten coating metal** of low melting point — zinc, tin, lead or aluminium.",
"",
"**Galvanising — zinc on iron or steel.**",
"*Process:* (i) **clean** by pickling in dilute H₂SO₄ at 60–90 °C for 15–20 minutes to remove scale and rust; (ii) wash and dry; (iii) treat with a **zinc ammonium chloride flux**; (iv) **dip in molten zinc at 425–450 °C**; (v) pass between rollers to control thickness, cool slowly and anneal.",
"",
"**How galvanisation prevents corrosion — the two mechanisms:**",
"",
"1. **Barrier protection.** The continuous zinc layer physically isolates the steel from moisture and oxygen, and zinc itself forms a tough adherent film of zinc oxide and basic carbonate that corrodes very slowly.",
"",
"2. **Sacrificial (cathodic) protection — the decisive advantage.** Zinc is **above iron in the galvanic series**, so wherever the coating is scratched, cut or drilled, the zinc becomes the **anode** and the exposed steel the **cathode**:",
"$$\\text{Zn} \\rightarrow \\text{Zn}^{2+} + 2e^-$$",
"The released electrons flow to the steel and suppress $\\text{Fe} \\rightarrow \\text{Fe}^{2+} + 2e^-$. The zinc corrodes **in place of** the iron, so **the steel does not rust even at the exposed scratch**.",
"",
"*Uses:* buckets, roofing sheets, pipes, wire, fencing, nails, bolts, transmission towers, automobile bodies.",
"*Limitation:* galvanised containers **must not store acidic foodstuffs**, because zinc dissolves into toxic soluble compounds.",
"",
"**Tinning — tin on iron.** The cleaned article passes through molten zinc chloride flux and then **molten tin at ~240 °C**. Tin is **non-toxic**, hence its use for food and oil containers and kitchen utensils. But since tin is **cathodic to iron**, a break in the coating causes rapid intense corrosion of the exposed steel.",
"",
"### Electroplating",
"",
"**Definition.** Deposition of a thin adherent layer of one metal on another by **electrolysis**.",
"",
"- **Cathode** — the article to be plated (negative terminal)",
"- **Anode** — usually the coating metal itself (soluble anode)",
"- **Electrolyte** — a salt solution of the coating metal, plus complexing agents, buffers and **addition agents** (glue, gelatin, brighteners) giving a smooth, fine-grained, bright deposit",
"- A **low-voltage DC supply**",
"",
"$$\\text{Cathode: } \\;\\text{Ni}^{2+} + 2e^- \\rightarrow \\text{Ni (deposited)}$$",
"$$\\text{Anode: } \\;\\text{Ni} \\rightarrow \\text{Ni}^{2+} + 2e^- \\;(\\text{replenishes the bath})$$",
"",
"Mass deposited follows **Faraday's laws**: $\\;w = \\dfrac{E\\,I\\,t}{F}$",
"",
"**Pre-treatment is critical** — degreasing, pickling, rinsing, sometimes electro-cleaning. Adhesion fails completely on a dirty surface.",
"",
"**How it prevents corrosion:** it provides a **continuous non-porous barrier**, with thickness and uniformity controlled precisely. Where the coating metal is anodic to the base (zinc plating) sacrificial protection is added; where it is cathodic (nickel, chromium, tin) protection depends entirely on continuity, which is why nickel-chromium plating is applied in multiple layers.",
"",
"**Objects and advantages:** corrosion resistance; **decorative appearance** (chromium, gold, silver); increased **hardness and wear resistance**; improved electrical conductivity of contacts; solderability; heat and chemical resistance; building up worn parts to size; reflectivity.",
"",
"*Applications:* automobile parts, taps and bathroom fittings, jewellery, electronic connectors, PCBs, tools.",
"",
"### Anodizing",
"",
"**Definition.** An **electrolytic passivation process** that thickens the natural oxide layer on a metal — chiefly **aluminium**, also magnesium and titanium.",
"",
"**Process.** The article is made the **ANODE** (hence the name — the opposite of electroplating) in dilute **sulphuric acid**, chromic or oxalic acid, with a lead or aluminium cathode:",
"",
"$$\\text{At the anode: } \\;2\\text{Al} + 3\\text{H}_2\\text{O} \\rightarrow \\text{Al}_2\\text{O}_3 + 6\\text{H}^+ + 6e^-$$",
"",
"This grows an oxide film **10 to 100 times thicker** than the natural one — typically 5–25 µm.",
"",
"**Sealing.** The fresh film is **porous**, which is what allows it to absorb dyes and gives anodised aluminium its colours. It is then **sealed** in boiling water or steam, hydrating the oxide to boehmite; the swelling closes the pores and makes the layer impervious.",
"",
"**How it prevents corrosion:** the film is **aluminium oxide — chemically inert, hard, and integral with the metal** rather than merely deposited on it, so it cannot peel or flake. It is a complete barrier against moisture and oxygen, and being an insulator it also prevents galvanic current flow.",
"",
"**Advantages:** excellent corrosion and abrasion resistance; cannot chip since it is part of the metal; can be **dyed in many colours**; electrically insulating; non-toxic; improves paint adhesion; UV stable.",
"",
"*Applications:* window and door frames, aircraft and automobile components, cookware, satellites, mobile phone and laptop bodies, architectural cladding.",
"",
"### Metal spraying (metallising)",
"",
"Molten coating metal is **atomised by compressed air** and sprayed onto a roughened cleaned surface, solidifying as a mechanically bonded layer. Zinc, aluminium, tin and lead are commonly sprayed.",
"",
"*Merits:* can be applied **on site** to very large structures — bridges, storage tanks, ship hulls — that cannot be dipped or plated; thickness easily controlled; almost any metal can be sprayed; the base metal is not significantly heated; local repair possible.",
"*Demerits:* somewhat porous, needing sealing; adhesion is mechanical, so grit blasting is essential; skilled operators required; material wastage.",
