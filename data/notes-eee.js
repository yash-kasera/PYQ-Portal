"## 5.6 Factors influencing the rate of corrosion",
"",
"### Nature of the metal",
"",
"1. **Position in the galvanic series** — the more active the metal, the greater its tendency; the larger the potential difference in a couple, the faster the attack",
"2. **Relative areas of anode and cathode** — a **small anode with a large cathode** gives intense, rapid, localised corrosion. **This is the single most important design consideration**",
"3. **Purity** — impurities create heterogeneity and set up local galvanic cells; purer metal is more resistant",
"4. **Physical state** — smaller grain size and stressed areas corrode faster",
"5. **Nature of the oxide film** — stable, non-porous, adherent films protect (Pilling–Bedworth ratio ≥ 1); porous or volatile ones do not",
"6. **Solubility of the corrosion product** — if soluble or volatile it dissolves away and corrosion continues; if insoluble and adherent it suppresses further attack. This is why **lead resists sulphuric acid** — insoluble PbSO₄ forms a barrier",
"7. **Hydrogen overvoltage** — a low overvoltage on the cathode accelerates corrosion",
"",
"### Nature of the environment",
"",
"8. **Temperature** — the rate roughly **doubles for every 10 °C rise**",
"9. **Humidity** — negligible in dry air but rising steeply above the **critical humidity** (~60–70 % for iron), because a moisture film provides the electrolyte",
"10. **Atmospheric impurities** — SO₂, CO₂, H₂S and NaCl (near the coast) form conducting acidic films and greatly accelerate attack",
"11. **pH** — corrosion rises sharply below pH 5; amphoteric metals (Al, Zn) also corrode in strong alkali",
"12. **Dissolved oxygen** — generally increases corrosion, but a *uniform* high concentration can promote passivation, whereas a *differential* concentration causes the most damage",
"13. **Conductivity of the medium** — seawater and saline soil support higher corrosion current",
"14. **Fluid velocity** — increases oxygen supply and strips protective films, causing erosion corrosion",
"",
