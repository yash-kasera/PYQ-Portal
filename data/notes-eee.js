"## 5.7 Corrosion control",
"",
"### Proper design — the first and cheapest defence",
"",
"1. **Avoid contact of dissimilar metals**; if unavoidable choose metals close in the galvanic series and **insulate the joint** with non-metallic gaskets and sleeves",
"2. **Make the anodic area large relative to the cathodic area** — never a small anodic fastener with a large cathodic plate",
"3. **Avoid crevices, sharp corners and re-entrant angles** where moisture and dirt collect. Use **butt welds in preference to riveted or bolted lap joints**; fill unavoidable crevices with a non-absorbent filler",
"4. **Provide complete drainage** — no trapped liquid; slope tank bottoms, put the drain at the lowest point, round internal corners",
"5. **Avoid sharp bends and sudden section changes** in piping, which cause turbulence and erosion corrosion",
"6. **Ensure free air circulation**; avoid enclosed pockets where humidity builds",
"7. **Allow a corrosion allowance** on wall thickness of critical components",
"8. **Make components accessible** for inspection, cleaning, maintenance and replacement",
"9. **Avoid or relieve stresses** — stress-relief annealing after welding and cold working",
"10. Prevent **direct contact with the ground**; mount on plinths",
"11. Avoid **dead spaces** where liquid stagnates",
"",
"### Material selection",
"",
"1. **Use pure metals** where practical",
"2. **Use corrosion-resistant alloys matched to the environment** — stainless steel for oxidising conditions, Monel for reducing, Hastelloy and titanium for severe service",
"3. **Select on the actual environment**, not general reputation. Stainless steel resists nitric acid superbly but **pits badly in chlorides**; lead is excellent in sulphuric but useless in nitric acid",
"4. Weigh **cost against service life** — an expensive alloy is economical if it avoids repeated replacement and downtime",
"5. Consider **mechanical properties, weldability and fabricability**, not corrosion resistance alone",
"6. Consider whether the corrosion product will **contaminate the product** — critical in food, pharmaceutical and electronic industries",
"",
"> **Why design and material selection matter most.** They are **preventive and permanent**, built into the structure at negligible extra cost, whereas coatings, inhibitors and cathodic protection need continuous expenditure and maintenance for the whole life of the plant. **A poorly designed structure will corrode however well it is protected afterwards.**",
"",
"### Cathodic protection",
"",
"The principle is to force the **entire structure to behave as a cathode**, so no part can act as an anode and dissolve.",
"",
"**(a) Sacrificial anodic protection.** A more active metal — **zinc, magnesium or aluminium** — is connected to the structure. Being higher in the galvanic series it becomes the **anode and corrodes preferentially**, while the structure becomes the cathode. The anode is consumed and periodically replaced — hence \"sacrificial\".",
"",
"```",
"        Mg / Zn block  (SACRIFICIAL ANODE — corrodes)",
"              │ electrical connection",
"        ══════╪═══════════════════════",
"          Buried steel pipeline (CATHODE — protected)",
"```",
"",
"*Applications:* buried pipelines and tanks, **ship hulls** (zinc blocks near the propeller), water heaters (a magnesium rod inside), offshore platforms, marine piers.",
"*Merits:* no external power needed; simple; no over-protection risk; good for remote locations.",
"*Demerits:* anodes are consumed and need replacement; limited driving voltage, so unsuitable for high-resistivity soils or very large structures.",
"",
"**(b) Impressed current cathodic protection.** An **external DC source** drives current from an **inert anode** (graphite, high-silicon iron, platinised titanium) onto the structure. The negative terminal connects to the structure.",
"*Merits:* adjustable driving voltage; protects very large structures; works in high-resistivity soil; long-lasting anodes.",
"*Demerits:* needs continuous power and monitoring; risk of over-protection causing hydrogen embrittlement and coating damage; interference with neighbouring structures.",
"",
"**(c) Anodic protection.** Only for metals that **passivate** (stainless steel, titanium, mild steel in H₂SO₄). A potentiostat holds the metal in its passive potential range. Used for sulphuric acid and fertiliser storage tanks.",
"",
"### Corrosion inhibitors",
"",
"A substance added in small quantity to the environment which markedly reduces the attack.",
"",
"**Anodic inhibitors** — form a **thin insoluble adherent film on the anodic areas**, passivating them. Examples: **chromates, phosphates, tungstates, molybdates, nitrites**.",
"",
"> **They are \"dangerous inhibitors\".** Used in **insufficient quantity**, the film covers most but not all of the anode; the remaining bare anode becomes very small relative to the cathode, and the result is **intense localised pitting — worse than no inhibitor at all**. Their concentration must be carefully maintained and monitored.",
"",
"**Cathodic inhibitors** — reduce the cathodic reaction.",
"*In acidic solution* (hydrogen evolution), organic inhibitors — **amines, mercaptans, thiourea, heavy metal soaps** — adsorb on cathodic sites, raising the **hydrogen overvoltage**.",
"*In neutral solution* (oxygen absorption), either **eliminate oxygen** with scavengers such as **sodium sulphite or hydrazine**, or add salts of **zinc, magnesium or nickel** whose ions precipitate insoluble hydroxides on the cathodic sites:",
"$$\\text{Zn}^{2+} + 2\\text{OH}^- \\rightarrow \\text{Zn(OH)}_2 \\downarrow$$",
"$$2\\text{Na}_2\\text{SO}_3 + \\text{O}_2 \\rightarrow 2\\text{Na}_2\\text{SO}_4$$",
"",
"*Cathodic inhibitors are inherently **safer** — under-dosing merely gives less protection rather than causing catastrophic pitting.*",
"",
"**Vapour phase inhibitors (VPI)** — volatile compounds such as **dicyclohexyl ammonium nitrite** which sublime and adsorb on metal surfaces inside sealed packages, protecting machinery and spares during storage and transport.",
