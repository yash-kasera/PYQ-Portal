"## 5.5 Types of corrosion",
"",
"### Galvanic (bimetallic) corrosion",
"",
"When two **dissimilar metals** are in electrical contact in an electrolyte, the metal **higher in the galvanic series (more active)** corrodes preferentially while the nobler one is protected.",
"",
"$$\\text{Zn} \\,|\\, \\text{Fe} \\Rightarrow \\text{Zn corrodes, Fe protected} \\qquad \\text{Fe} \\,|\\, \\text{Cu} \\Rightarrow \\text{Fe corrodes rapidly}$$",
"",
"> **The area ratio is decisive.** A **small anode with a large cathode** is the worst possible combination, since the whole corrosion current concentrates on a tiny area. Steel rivets in a copper plate fail rapidly; copper rivets in a steel plate are far less damaging.",
"",
"**Prevention:** avoid coupling dissimilar metals; if unavoidable choose metals close together in the series; **insulate the joint** with non-conducting gaskets and washers; make the anode area large; coat both metals (never the anode alone).",
"",
"### Concentration cell / differential aeration corrosion",
"",
"**The most common type in practice.** It occurs when one part of a metal is exposed to a **different oxygen concentration** than another part of the same metal.",
"",
"$$\\boxed{\\text{The poorly oxygenated part becomes the ANODE and corrodes.}}$$",
"$$\\boxed{\\text{The well oxygenated part becomes the CATHODE and is protected.}}$$",
"",
"This seems counter-intuitive — the part with *less* oxygen corrodes — but it follows from the electrode reactions: the oxygen-rich region can sustain the cathodic reduction, forcing the oxygen-poor region to supply the electrons by dissolving.",
"",
"**(a) Wire fence.** The **crossings and points of contact** are shielded from air while the open portions are freely exposed, so the crossings become anodic and **corrode first** — exactly what is observed in practice, and the standard illustration.",
"",
"**(b) Waterline corrosion.** In a steel tank of standing water, the portion **just below the waterline** is poorly oxygenated compared with the surface region in contact with air. A concentration cell forms and the area **immediately below the waterline becomes anodic**, producing a distinct groove of attack. Ships' hulls suffer this severely; countered by anti-corrosive paints.",
"",
"**(c) Pitting corrosion.** A **dust particle, scale or water drop** rests on the surface. The metal **beneath the deposit** receives little oxygen and becomes anodic; the surrounding exposed metal is cathodic. Because the anodic area is minute and the cathodic area large, the current density at the anode is enormous and a deep narrow **pit** bores into the metal.",
"",
"> **Why pitting is so dangerous:** total metal loss is trivial, so a component looks almost undamaged, yet a pit can perforate a pipe wall or pressure vessel and cause sudden failure. It is also **autocatalytic** — the pit becomes more acidic and oxygen-starved as it deepens, accelerating its own growth. Stainless steels in chloride environments are especially susceptible.",
"",
"**(d) Crevice corrosion** — under bolt heads, gaskets, washers and lap joints.",
"**(e) Underground pipelines** passing through soils of differing aeration — clay (poorly aerated, anodic) and sand (well aerated, cathodic).",
"",
"### Stress corrosion cracking",
"",
"The combined action of a **tensile stress** and a **specific corrosive environment** produces fine cracks that propagate through the metal, causing sudden brittle failure with almost no visible general corrosion. Residual stresses from cold working, welding or machining suffice.",
"",
"**Classic cases:** *caustic embrittlement* of boiler steel in alkaline water; *season cracking* of cold-worked brass in ammonia; stainless steel in hot chlorides.",
"*Prevention:* **stress-relief annealing**; changing the environment or adding inhibitors; resistant alloys; **shot peening** to introduce compressive surface stress.",
"",
"### Corrosion by seawater",
"",
"Seawater is particularly aggressive because it is a **strong electrolyte** (~3.5 % salts, mainly NaCl) with high conductivity; it contains **chloride ions** that break down passive films and initiate pitting; it is well oxygenated near the surface; and it adds **erosion by wave action** and **biofouling** which creates differential aeration cells. The **splash zone** and **waterline** suffer worst.",
"",
"### Other forms",
"",
"**Intergranular corrosion** — attack along grain boundaries; *weld decay* in stainless steel from chromium carbide precipitation. **Erosion corrosion** — combined wear and corrosion in fast-flowing fluids, at pipe bends and impellers. **Cavitation corrosion** — collapsing vapour bubbles on propellers and turbine blades. **Selective leaching (dezincification)** — one alloy component removed. **Microbiologically influenced corrosion.** **Fretting corrosion** at vibrating contacts.",
"",
