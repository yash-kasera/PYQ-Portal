"",
"**By nature:** biodegradable (wet) versus non-biodegradable (dry); recyclable; combustible versus non-combustible.",
"",
"### Objectives of solid waste management",
"",
"1. **Protect public health** — prevent breeding of flies, mosquitoes and rodents and the spread of disease",
"2. **Protect the environment** — prevent soil, water and air pollution",
"3. **Conserve resources** through recovery, recycling and reuse",
"4. **Recover energy**",
"5. **Minimise the quantity requiring final disposal**, and hence the land needed",
"6. **Maintain aesthetics** and civic cleanliness",
"7. **Reduce greenhouse emissions** — landfills are a major methane source",
"8. Provide a **cost-effective and socially acceptable** service",
"9. Ensure **occupational safety** of waste handlers",
"",
"### Functional elements",
"",
"$$\\text{Generation} \\rightarrow \\text{Storage} \\rightarrow \\text{Collection} \\rightarrow \\text{Transfer \\& Transport} \\rightarrow \\text{Processing} \\rightarrow \\text{Disposal}$$",
"",
"**Segregation at source** is the single most important step — into **wet, dry and hazardous** streams (green, blue and black bins). Segregated waste can be processed; mixed waste usually cannot. **Collection** is the most expensive element, typically 60–70 % of the budget.",
"",
"### Methods of treatment and disposal",
"",
"**1. Sanitary landfill.** Waste is spread in thin layers in a prepared lined depression, compacted, and covered with 15–30 cm of earth daily, forming **cells**. Finally capped with clay and vegetated.",
"",
"*Essential engineering:* an **impermeable liner** (clay + HDPE geomembrane); a **leachate collection and treatment system**; a **gas venting or recovery system** for landfill methane; groundwater monitoring wells; and post-closure care for 15–30 years.",
"",
"*Merits:* simple, economical, handles all waste types, reclaims low-lying land, methane recoverable as energy.",
"*Demerits:* large land area near cities where land is costly; **leachate contaminates groundwater** if the liner fails; methane is a potent greenhouse gas and explosion hazard; odour, flies, birds; public opposition; permanent liability.",
"",
"> **Open dumping is NOT landfilling.** It is simply tipping waste on vacant land — the worst practice, with all the problems and none of the safeguards. It is prohibited under Indian rules.",
"",
"**2. Composting.** Controlled **aerobic** decomposition of the biodegradable fraction into a stable humus-like manure. Methods: windrow, aerated static pile, in-vessel, and **vermicomposting** with earthworms (*Eisenia foetida*).",
"",
"*Merits:* converts waste into a valuable soil conditioner; reduces volume 50–60 %; low cost and technology; suited to Indian waste which is 40–60 % organic; possible at household level.",
"*Demerits:* needs source segregation; slow (4–8 weeks); requires land; odour if it turns anaerobic; limited market; heavy metals if feedstock is contaminated.",
"",
"**3. Incineration.** Controlled combustion at 900–1200 °C.",
"*Merits:* reduces volume 80–90 %; **destroys pathogens completely**, making it the method of choice for **biomedical waste**; energy recovery (**waste-to-energy**); little land; works in any weather.",
"*Demerits:* very high capital and operating cost; emits **dioxins, furans, heavy metals, NOₓ** unless expensive flue-gas cleaning is fitted; ash residue is hazardous; Indian MSW has high moisture and low calorific value so auxiliary fuel is often needed; discourages recycling.",
"",
"**4. Pyrolysis / gasification** — thermal decomposition without (or with limited) oxygen, giving fuel gas, oil and char. Cleaner than incineration but technically demanding.",
"",
"**5. Anaerobic digestion (biomethanation)** — decomposition without oxygen in a closed digester, producing **biogas** and digestate manure. Excellent for wet market and canteen waste; **captures methane instead of releasing it**.",
"",
"**6. Recycling** — paper, glass, metal, plastics recovered at material recovery facilities. Recycling aluminium saves **95 %** of the energy of primary production.",
"",
"**7. Refuse-derived fuel (RDF)** — high-calorific dry combustibles shredded and pelletised for cement kilns and power plants.",
"",
"### Recommended measures for proper management",
"",
"1. **Follow the waste hierarchy:**",
"$$\\text{Refuse} \\rightarrow \\text{Reduce} \\rightarrow \\text{Reuse} \\rightarrow \\text{Recycle} \\rightarrow \\text{Recover energy} \\rightarrow \\text{Dispose}$$",
"2. **Mandatory segregation at source**",
"3. **100 % door-to-door collection**; abolish open dumping",
"4. **Decentralised processing** so only inert residue travels to landfill",
"5. **Extended Producer Responsibility (EPR)** — manufacturers responsible for collecting and recycling their packaging and products",
"6. **Ban single-use plastics**",
"7. **Scientific sanitary landfills** for inert residue only; remediate legacy dumps by **bio-mining**",
"8. **Integrate the informal sector** — ragpickers already recover much of the recyclables and should be organised, protected and fairly paid",
"9. Separate systems for **biomedical and e-waste** under their respective Rules",
"10. **Public awareness**; user fees and penalties",
"11. **Solid Waste Management Rules 2016**, Plastic Waste Rules, **Swachh Bharat Mission**",
"12. Capacity building and adequate funding for urban local bodies",
