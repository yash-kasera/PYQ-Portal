"## 5.4 Electrochemical and galvanic series",
"",
"The **electrochemical series** arranges metals by standard electrode potential:",
"",
"$$\\text{K} > \\text{Ca} > \\text{Na} > \\text{Mg} > \\text{Al} > \\text{Zn} > \\text{Fe} > \\text{Ni} > \\text{Sn} > \\text{Pb} > \\text{H} > \\text{Cu} > \\text{Ag} > \\text{Au}$$",
