"## 3.5 Disaster management",
"",
"A **disaster** is a sudden calamitous event seriously disrupting a community and causing losses exceeding its own coping capacity.",
"",
"$$\\text{Risk} = \\frac{\\text{Hazard} \\times \\text{Vulnerability}}{\\text{Capacity}}$$",
"",
"### The disaster management cycle",
"",
"| Phase | When | Activities |",
"|---|---|---|",
"| **Mitigation** | Before | Structural and non-structural risk reduction — building codes, land-use planning, embankments |",
"| **Preparedness** | Before | Early warning, evacuation plans, mock drills, stockpiling, training |",
"| **Response** | During / immediately after | Search and rescue, evacuation, first aid, shelter, food, water |",
"| **Recovery** | After | Restoring services, rebuilding, livelihoods, psychosocial care — **building back better** |",
"",
"India's framework: the **Disaster Management Act 2005**, the **NDMA** chaired by the Prime Minister, State and District Authorities, and the **NDRF**.",
"",
"### Earthquakes",
"",
"**Cause.** Sudden release of accumulated strain along a fault, generating seismic waves; most occur at **tectonic plate boundaries**. The Himalayan belt results from the Indian plate colliding with the Eurasian plate. India has **four seismic zones (II–V)**; Zone V (Kashmir, Himachal, Uttarakhand, North-East, Kutch, Andaman) is most severe.",
"",
"**Effects.** Collapse of buildings — *most deaths are caused by collapsing structures, not by the shaking itself*; fires from ruptured gas lines; landslides; **liquefaction** of saturated soils; dam failure; tsunamis if offshore; disruption of water, power and communication; disease outbreaks.",
"",
"**Management.**",
"*Before* — **seismic zoning and microzonation**; enforce **earthquake-resistant building codes (IS 1893, IS 13920)** — the single most effective measure; retrofitting; base isolation and shear walls; avoid construction on soft or filled ground; **mock drills** teaching \"drop, cover, hold\"; emergency kits; secure heavy furniture.",
"*During* — take cover under sturdy furniture away from windows; outdoors move to open ground away from buildings and power lines; do not use lifts.",
"*After* — expect aftershocks; evacuate damaged buildings; shut off gas and electricity; search and rescue; first aid, shelter, clean water, sanitation; structural assessment before re-occupation.",
"",
"### Floods",
"",
"**Causes.** Heavy or prolonged rainfall and cloudbursts; inadequate channel capacity; **deforestation** increasing runoff; **siltation** reducing capacity; **encroachment on floodplains and wetlands**; poor urban drainage; dam or embankment failure; cyclonic storm surge; glacial lake outburst.",
"",
"**Consequences.**",
"1. **Loss of life** — drowning",
"2. Destruction of houses, roads, bridges, power and communication",
"3. **Crop destruction and food shortage**; loss of livestock",
"4. **Contamination of drinking water** and epidemics — cholera, typhoid, hepatitis — and vector-borne disease after the water recedes",
"5. **Soil erosion** and sand deposition on farmland",
"6. Displacement; industrial and economic loss",
"7. Waterlogging, salinity, ecosystem damage",
"",
"**Control.**",
"*Structural* — **embankments and levees**; **dams and detention reservoirs**; **channel improvement and desilting**; **diversion channels and spillways**; improved urban storm drainage; raised flood shelters.",
"*Non-structural* — **flood forecasting and early warning** (CWC and IMD, satellite and radar); **floodplain zoning** legally restricting construction; **afforestation and watershed management**; protection of **wetlands and natural drainage** which act as sponges; **flood insurance**; evacuation plans, boats and trained NDRF teams.",
"",
"### Landslides",
"",
"**Causes.** Steep slopes with weak or weathered rock; heavy rainfall saturating and lubricating the slope; earthquakes; **deforestation** removing root binding; unscientific **road cutting and hill construction**; mining and quarrying; toe erosion by rivers; unplanned tourism.",
"",
"**Effects.** Burial of villages and roads; blocking of rivers creating landslide lakes that later burst; loss of life, farmland and forest; disruption of hill transport; economic loss.",
"",
