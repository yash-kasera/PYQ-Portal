"## 3.3 Nuclear pollution and hazards",
"",
"**Definition.** Release into the environment of radioactive substances emitting **ionising radiation** — alpha, beta, gamma and neutrons — which damage living tissue.",
"",
"### Sources",
"",
"**Natural** — cosmic rays, radon from soil and rock, K-40, U-238, Th-232 (the natural background).",
"**Man-made** — nuclear power plants; uranium mining and milling tailings; **weapon testing** fallout (Sr-90, Cs-137, I-131); waste disposal; medical uses (X-rays, radiotherapy); industrial radiography and tracers.",
"",
"### Classification of nuclear waste",
"",
"| Level | Source | Handling |",
"|---|---|---|",
"| **Low (LLW)** | Contaminated clothing, tools, filters | Shallow burial after compaction |",
"| **Intermediate (ILW)** | Reactor components, resins, sludge | Solidified in cement or bitumen, buried |",
"| **High (HLW)** | Spent fuel, reprocessing liquid | **Vitrification** in borosilicate glass, decades of cooling, then deep geological disposal |",
"",
"### Pollution from nuclear power plants",
"",
"1. **Radioactive gaseous releases** — small routine emissions of Kr-85, Xe-133, tritium, I-131",
"2. **Liquid effluent** containing tritium and activation products",
"3. **Spent fuel** — intensely radioactive, containing **plutonium-239 with a half-life of 24,000 years**; hazardous for hundreds of thousands of years, with **no operating permanent repository anywhere in the world**",
"4. **Thermal pollution** — about one-third more waste heat per unit of electricity than coal, because of the lower steam temperature",
"5. **Mining and milling waste** — tailings emit radon and contaminate groundwater",
"6. **Accidental release** — the catastrophic risk",
"7. **Decommissioning waste**",
"",
"### Health hazards",
"",
"**Somatic effects** (in the exposed individual):",
"- **Acute (deterministic)** — high dose in a short time. **Acute radiation syndrome**: nausea, vomiting, hair loss, bone marrow destruction, damage to the intestinal lining, haemorrhage, infection, death. Skin burns, cataracts, sterility",
"- **Chronic (stochastic)** — low dose over a long time. **Cancers** — leukaemia, thyroid, lung, bone, breast — appearing years or decades later. No threshold dose is assumed",
"",
"**Genetic effects** — radiation causes **mutations in germ cells**, so the damage is transmitted to descendants: congenital deformities, stillbirths, mental retardation and hereditary disease in generations **never themselves exposed**. This is what makes radiation uniquely serious among pollutants.",
"",
"Measured in **gray (Gy)** for absorbed dose and **sievert (Sv)** for biological equivalent dose. Bone marrow, intestinal lining, gonads and the developing foetus are most sensitive.",
"",
"### The Chernobyl disaster (26 April 1986)",
"",
"**What happened.** During a poorly planned safety test at **Reactor 4** in Pripyat, Ukraine, operators disabled safety systems and withdrew nearly all control rods. The RBMK design had a **positive void coefficient** — steam formation *increased* reactivity — which with a flawed control-rod design produced an uncontrollable power surge to about 100 times normal in seconds. Two explosions blew off the 1000-tonne reactor lid and the graphite moderator burned for ten days.",
"",
"**Consequences:**",
"- A plume of I-131, Cs-137 and Sr-90 spread over Belarus, Ukraine, Russia and much of Europe — the **largest uncontrolled release of radioactivity in history**, some 400 times the Hiroshima bomb",
"- 31 immediate deaths among firefighters and plant workers",
"- Over **350,000 permanently evacuated**; a 30 km **exclusion zone** remains uninhabitable",
"- A sharp, well-documented rise in **thyroid cancer in children** exposed to I-131 through contaminated milk",
"- Long-term leukaemia and other cancers; congenital deformities; severe psychological trauma",
"- Vast farmland and forest contaminated as far as Britain and Scandinavia",
"",
"**Lessons.** Reactor design must be *inherently* safe (negative void coefficient); containment structures are essential (Chernobyl had none of Western type); safety culture matters as much as engineering; and contamination respects no national boundary. It led to the **Convention on Nuclear Safety** and the IAEA's INES scale, on which Chernobyl and Fukushima are the only Level 7 events.",
"",
"### Control and remedial measures",
"",
"1. **Containment** — thick concrete and steel buildings around every reactor",
"2. **Defence in depth** — multiple independent safety systems and passive features working without power or operator action",
"3. **Shielding** — lead, concrete, water; remote handling and robots",
"4. **ALARA principle** — As Low As Reasonably Achievable; time, distance, shielding",
"5. **Personal dosimeters**, dose limits, regular health monitoring",
"6. **Waste treatment** — vitrification, long cooling, deep geological repositories in stable rock",
"7. **Strict siting** — away from dense population, seismic zones, coastal flood risk",
"8. **Regulation** — the Atomic Energy Regulatory Board in India, the IAEA internationally",
"9. **Emergency preparedness** — evacuation plans, **potassium iodide tablets** to block thyroid uptake of I-131, public warning systems",
"10. Ban on atmospheric testing; non-proliferation agreements; environmental radiation monitoring",
"",
