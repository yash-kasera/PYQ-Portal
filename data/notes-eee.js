"**Definition.** Degradation of water quality by any process that changes the ambient water temperature — most commonly discharge of heated cooling water.",
"",
"### Sources",
"",
"1. **Thermal and nuclear power plants** — by far the largest; a station may return tens of thousands of m³/h of water 8–10 °C hotter. A nuclear plant rejects even more heat per unit of electricity than a coal plant",
"2. **Industrial cooling water** — steel, paper, refineries, chemicals, textiles",
"3. **Deforestation of riverbanks**, removing shade",
"4. **Urban runoff** heated by roads and roofs",
"5. **Soil erosion** raising turbidity so water absorbs more solar heat",
"6. **Reservoirs** — surface warms; cold hypolimnetic release causes *cold-water* thermal pollution",
"",
"### Effects",
"",
"**1. Reduction in dissolved oxygen — the fundamental damage.** The solubility of oxygen **falls as temperature rises**, while warmth simultaneously **increases the metabolic rate** and hence the oxygen demand of aquatic organisms. **Supply falls while demand rises** — this double effect can suffocate fish.",
"",
"2. **Thermal shock** — sudden change kills fish and invertebrates, especially eggs and larvae",
"3. **Disruption of reproduction and migration** — spawning is temperature-triggered; warming causes untimely spawning and hatching failure",
"4. **Change in species composition** — cold-water species (trout, salmon) disappear, replaced by heat-tolerant ones; **biodiversity falls**",
"5. **Increased toxicity** of cyanides, heavy metals and pesticides at higher temperature, on organisms already heat-stressed",
"6. **Eutrophication and algal blooms**, whose decay depletes oxygen further",
"7. Faster decomposition of organic matter, consuming still more oxygen",
"8. Growth of pathogenic bacteria and fungi; more fish disease",
"9. Loss of aesthetic and recreational value",
"",
"### Control measures",
"",
"1. **Cooling ponds** — a large shallow reservoir cooling by evaporation and radiation. Simple but land-hungry",
"2. **Cooling towers** — the standard solution",
"   - **Wet (evaporative)** — water sprayed over fill, air drawn through; cooling mainly by evaporation. Effective but consumes water and produces a visible plume",
"   - **Dry** — heat transferred through a heat exchanger with no evaporation. No water loss but less efficient and costlier",
"3. **Cogeneration / waste heat utilisation** — the rejected heat is used for district heating, greenhouse warming, **aquaculture**, desalination or process heat. This turns the pollutant into a resource",
"4. **Artificial lakes and spray ponds**",
"5. **Improving plant thermal efficiency** so less waste heat is produced at all",
"6. **Diffusers** promoting rapid mixing rather than a single hot outfall",
"7. Maintaining **riparian vegetation** to shade streams",
"8. Regulation — a maximum permissible temperature rise at discharge, typically 5 °C above ambient",
"",
"### Waste management in thermal power plants",
"",
"| Waste | Management |",
"|---|---|",
"| **Fly ash** (60–80 % of ash) | Captured by **electrostatic precipitators** (>99 %); used in cement, bricks, concrete, road embankments, mine filling. Utilisation is **mandatory** in India |",
"| **Bottom ash** | Construction fill, brick making |",
"| **Flue gases** | ESP for particulates, **FGD scrubbers** for SO₂, low-NOₓ burners, tall stacks |",
"| **Cooling water** | Cooling towers and ponds |",
"| **Waste water** | Treatment, neutralisation, recycling, zero liquid discharge |",
"| **Coal dust and noise** | Dust suppression sprays, enclosed conveyors, green belts |",
"",
"Best practice: 100 % ash utilisation, closed-cycle cooling, lined ash ponds, continuous emission monitoring, a green belt over 33 % of plant area, and a shift to **supercritical and ultra-supercritical boilers** which burn less coal per unit.",
"",
