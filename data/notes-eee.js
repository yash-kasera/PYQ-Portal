"",
"### Tsunami and the 2004 Asian earthquake",
"",
"**Definition.** A series of very long-wavelength ocean waves generated by sudden vertical displacement of a large volume of water — usually an undersea earthquake, but also submarine landslides, volcanic eruptions or meteorite impact.",
"",
"**Characteristics.** In deep ocean the wave height is under a metre and the wavelength hundreds of kilometres, so it passes unnoticed beneath ships while travelling at **700–800 km/h**. Entering shallow water the speed falls and energy is compressed vertically, so the height builds dramatically (**shoaling**). A tell-tale warning is the sudden **withdrawal of the sea**, exposing the seabed, before the crest arrives.",
"",
"**The 2004 Indian Ocean event (26 December 2004).** An undersea **megathrust earthquake of magnitude 9.1–9.3** off northern Sumatra, where the Indian plate subducts beneath the Burma plate — the third-largest ever recorded, with the longest rupture ever observed (~10 minutes). The seafloor was thrust up several metres.",
"",
"*Consequences:*",
"- Approximately **230,000–280,000 killed** in 14 countries — the **deadliest tsunami in recorded history**",
"- Worst affected: Indonesia (Aceh, ~170,000), Sri Lanka, India (Tamil Nadu, Andhra Pradesh, Kerala, Andaman & Nicobar — over 12,000) and Thailand",
"- Waves up to **30 m**; inundation several kilometres inland",
