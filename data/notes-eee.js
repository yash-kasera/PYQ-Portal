"- Massive economic loss and long-term livelihood destruction",
"",
"*Why the toll was so high:* there was **no tsunami warning system in the Indian Ocean**; coastal populations did not know the warning signs; **mangrove belts** that would have absorbed wave energy had been cleared for aquaculture and tourism; and construction had been permitted right up to the shoreline.",
"",
"*Measures since:*",
"1. **Indian Ocean Tsunami Warning System**, with India's **INCOIS at Hyderabad** operating a national centre using seismic stations, deep-ocean pressure recorders and tide gauges",
"2. **Coastal Regulation Zone** enforcement",
"3. **Restoration of mangroves, coral reefs and shelter belts**, which demonstrably reduced damage where they existed",
"4. **Vertical evacuation shelters** and raised platforms",
"5. Community awareness, signposted evacuation routes, regular mock drills",
"6. Integration into the **Disaster Management Act 2005** and NDMA guidelines",
