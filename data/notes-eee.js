"**Advantages/uses:** predicts which metal is anodic in a couple; predicts cell feasibility and EMF; predicts displacement reactions; indicates relative reducing power; predicts hydrogen liberation from acids; guides the choice of sacrificial anodes.",
"",
"*Limitation for corrosion work:* it applies only to **pure metals in their own salt solutions under standard conditions**, whereas real corrosion involves alloys in seawater, soil or industrial atmospheres. The **galvanic series** — determined experimentally in seawater and including alloys — is the more reliable engineering guide. In it, *passive* stainless steel appears near the noble end while *active* stainless steel appears near the base end, a distinction impossible in the electrochemical series.",
