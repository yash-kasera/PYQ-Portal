"## 5.1 Process versus thread",
"",
"| Point | **Process** | **Thread** |",
"|---|---|---|",
"| Definition | A program in execution | A lightweight sub-unit of a process |",
"| Memory | **Own separate address space** | **Shares** the process's memory and files |",
"| Creation cost | Heavy — the OS allocates new memory | Light — only a stack and program counter |",
"| Context switch | Slow | Fast |",
"| Communication | IPC — pipes, sockets, shared memory | Direct, through shared variables |",
"| Isolation | One crash does not affect others | An uncaught error can bring down the process |",
"| Also called | Heavyweight | **Lightweight** |",
"",
"**Multiprocessing** runs several *processes*; **multithreading** runs several *threads* inside one process. Multithreading is faster and uses less memory, but requires careful **synchronization** because the threads share data.",
"",
"---",
"",
"## 5.2 Thread life cycle",
"",
"```",
"                start()          scheduler picks it",
"   ┌─────┐  ────────────▶ ┌──────────┐ ─────────────▶ ┌─────────┐",
"   │ NEW │                │ RUNNABLE │◀───────────    │ RUNNING │",
"   └─────┘                └──────────┘   yield /      └────┬────┘",
"                               ▲       time slice ends     │",
"                               │  notify(), timeout,       │ sleep(), wait(),",
"                               │  I/O complete             ▼ join(), blocking I/O",
"                               └─────────────────  ┌──────────────┐",
"                                                   │ BLOCKED /    │",
"                                                   │ WAITING /    │",
"                                                   │ TIMED_WAITING│",
"                    run() returns  ──▶             └──────────────┘",
"                          ┌────────────┐",
"                          │ TERMINATED │",
"                          └────────────┘",
"```",
"",
"| State | Meaning |",
"|---|---|",
"| **NEW** | Object created, `start()` not yet called |",
"| **RUNNABLE** | Ready to run, waiting for the CPU |",
"| **RUNNING** | Actually executing |",
"| **BLOCKED** | Waiting to acquire a monitor lock |",
"| **WAITING** | Waiting indefinitely — `wait()`, `join()` |",
"| **TIMED_WAITING** | Waiting for a set time — `sleep(t)` |",
"| **TERMINATED** | `run()` has completed |",
"",
"---",
"",
"## 5.3 The two ways of creating a thread",
"",
"### Method 1 — extend `Thread`",
"",
"```java",
"class MyThread extends Thread {",
"    private String name;",
"    MyThread(String name) { this.name = name; }",
"    @Override public void run() {",
"        for (int i = 1; i <= 5; i++) {",
"            System.out.println(name + \" : \" + i);",
"            try { Thread.sleep(300); } catch (InterruptedException e) { }",
"        }",
"    }",
"}",
"new MyThread(\"Thread-A\").start();      // start() — NOT run()",
"```",
"",
"### Method 2 — implement `Runnable`",
"",
"```java",
"class MyTask implements Runnable {",
"    @Override public void run() { System.out.println(\"running\"); }",
"}",
"Thread t = new Thread(new MyTask());",
"t.start();",
"",
"// Java 8 lambda — Runnable is a functional interface:",
"new Thread(() -> System.out.println(\"Lambda thread\")).start();",
"```",
"",
"### Which is preferred, and why",
"",
"**`Runnable` is preferred**, for four reasons:",
"",
"1. **Java allows only single inheritance.** Extending `Thread` consumes the one `extends` slot, so the class can never extend anything else. `Runnable` leaves it free.",
"2. **Better separation of concerns** — `Runnable` is the *task*; `Thread` is the *worker*. Mixing them is poor design.",
"3. **Reusability** — one `Runnable` can be given to several threads or submitted to an `ExecutorService` thread pool.",
"4. **Loose coupling** — the task does not inherit the many `Thread` methods it does not need.",
"",
"> **The most important single point in this module:** always call **`start()`**, never `run()`. Calling `run()` directly simply executes the method on the *current* thread — **no new thread is created at all**.",
"",
