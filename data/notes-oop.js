"## 3.2 Association, aggregation and composition",
"",
"These are the ways objects relate **without** inheritance. All three model **\"has-a\"**, differing in the strength of the bond.",
"",
"### Association — the most general",
"",
"Two objects are **aware of each other** and interact, but neither owns the other; both have independent lifetimes.",
"",
"```java",
"class Doctor {",
"    void treat(Patient p) { System.out.println(\"treating \" + p.getName()); }",
"}",
"// A doctor treats many patients; a patient sees many doctors.",
"// Deleting one does not delete the other.",
"```",
"",
"**Multiplicity (cardinality):**",
"",
"| Type | Meaning | Example |",
"|---|---|---|",
"| **One-to-one** | One of A relates to exactly one of B | A `Person` has one `Passport` |",
"| **One-to-many** | One of A relates to many of B | A `Department` has many `Teachers` |",
"| **Many-to-one** | Many of A relate to one of B | Many `Students` in one `College` |",
"| **Many-to-many** | Many of A relate to many of B | `Students` enrol in many `Courses` |",
"",
"```",
"  ┌─────────┐  1        *  ┌─────────┐",
"  │ College ├──────────────┤ Student │      one-to-many",
"  └─────────┘              └─────────┘",
"",
"  ┌─────────┐  1        1  ┌──────────┐",
"  │ Person  ├──────────────┤ Passport │     one-to-one",
"  └─────────┘              └──────────┘",
"```",
"",
"### Aggregation — a *weak* has-a",
"",
"A \"part of\" relationship where the part **can exist independently** of the whole. UML: **hollow diamond ◇**.",
"",
"```java",
"class Student {",
"    private Address address;              // aggregation",
"    Student(String name, Address address) {",
"        this.address = address;           // the Address was created OUTSIDE",
"    }",
"}",
"Address addr = new Address(\"Jabalpur\", \"MP\");",
"Student s1 = new Student(\"Yash\", addr);",
"Student s2 = new Student(\"Riya\", addr);   // the SAME Address is shared",
"// If s1 and s2 are destroyed, addr still exists.",
"```",
"",
"### Composition — a *strong* has-a",
"",
"The part **cannot exist without** the whole; the whole controls the part's lifetime. UML: **filled diamond ◆**.",
"",
"```java",
"class Car {",
"    private final Engine engine = new Engine();   // created INSIDE — composition",
"    void drive() { engine.start(); }",
"}",
"// Destroy the Car and the Engine goes with it.",
"```",
"",
"### Comparison",
"",
"| Point | **Association** | **Aggregation** | **Composition** |",
"|---|---|---|---|",
"| Relationship | \"uses-a\" | \"has-a\" (weak) | \"part-of\" (strong) |",
"| Ownership | None | Weak — part is shared | **Strong — part is owned** |",
"| Lifetime | Fully independent | Part outlives the whole | **Part dies with the whole** |",
"| UML symbol | Plain line | Hollow diamond ◇ | Filled diamond ◆ |",
"| Object created | Outside | Outside, passed in | **Inside** the owner |",
"| Sharing | Possible | Possible | **Not possible** |",
"| Example | Doctor – Patient | Department – Teacher | Car – Engine |",
"",
"> **The hierarchy:** every composition is an aggregation, and every aggregation is an association — but not the reverse.",
"",
"### Types of aggregation",
"",
"| Type | Meaning |",
"|---|---|",
"| **Fixed** | Number and type of parts fixed at design time (a `Bicycle` always has 2 `Wheel`s) |",
"| **Variable** | Number of parts varies at run time, levels fixed (a `Company` has many `Employees`) |",
"| **Recursive** | An object contains instances of its own type (a `Directory` contains `Directory` objects) |",
"",
"{{PYQ:association-aggregation}}",
