"## 3.3 Abstract classes",
"",
"An **abstract class** cannot be instantiated. It exists to be extended, stating a common contract plus some shared implementation.",
"",
"**Rules:**",
"1. Declared with `abstract class`",
"2. May contain **abstract methods** (no body) **and concrete methods** (with body)",
"3. If a class has even one abstract method, the class **must** be abstract",
"4. A subclass must implement **all** inherited abstract methods, or itself be abstract",
"5. It **can** have constructors, instance variables, static methods and any access modifier",
"6. It cannot be `final`",
"",
"### Can we create an object of an abstract class?",
"",
"**No — and here is why.** An abstract class is *incomplete*: it declares methods with no implementation. If an object could be created, calling such a method would have no code to execute. The compiler therefore rejects it.",
"",
"```java",
"abstract class Shape {",
"    abstract double area();",
"    void show() { System.out.println(\"Area = \" + area()); }",
"}",
"// Shape s = new Shape();     ← COMPILE ERROR",
"Shape s = new Circle(5);      // ✔ parent reference, concrete subclass object",
"```",
"",
"> **Two nuances worth stating for full marks:** (a) you *can* hold an abstract-class **reference** pointing to a subclass object — that is exactly how run-time polymorphism works; (b) an abstract class **does have a constructor**, which runs via `super()` when a subclass object is created. You can also create an **anonymous concrete subclass** on the spot, which looks like instantiating the abstract class but is not.",
"",
"---",
"",
"## 3.4 Interfaces",
"",
"An **interface** is a fully abstract type specifying **what** a class must be able to do, saying nothing about how.",
"",
"```java",
"interface Drawable {",
"    int MAX = 100;                 // implicitly public static final",
"    void draw();                   // implicitly public abstract",
"}",
"class Circle implements Drawable {",
"    public void draw() { System.out.println(\"Drawing circle\"); }",
"}",
"```",
"",
"**Rules:**",
"1. All methods are implicitly `public abstract` (before Java 8)",
"2. All fields are implicitly `public static final` — constants",
"3. Cannot be instantiated; has no constructor",
"4. A class **implements** an interface; an interface **extends** another interface",
"5. Since **Java 8**: `default` and `static` methods with bodies are allowed; since **Java 9**: `private` methods too",
"",
"### Can an interface extend another interface?",
"",
"**Yes** — using `extends` (not `implements`), and it may extend **several**:",
"```java",
"interface Printable { void print(); }",
"interface Showable extends Printable { void show(); }   // interface extends interface",
"interface Both extends Printable, Showable { }          // multiple — allowed here",
"",
"class Document implements Showable {",
"    public void print() { }   // inherited from Printable",
"    public void show()  { }   // from Showable",
"}",
"```",
"A class implementing the child must implement **every** method in the whole chain.",
"",
"### Abstract class versus interface",
"",
"| Point | **Abstract class** | **Interface** |",
"|---|---|---|",
"| Keyword | `abstract class` | `interface` |",
"| Inherited by | `extends` | `implements` |",
"| Methods | Abstract **and** concrete | Abstract (+ default/static since Java 8) |",
"| Variables | Any kind — final, non-final, static, instance | Only `public static final` |",
"| Access modifiers | Any | Members implicitly public |",
"| Constructor | **Yes** | **No** |",
"| Multiple inheritance | Not supported | **Supported** |",
"| State | Can hold instance state | Cannot |",
"| When to use | Related classes sharing common code | Unrelated classes sharing a capability |",
"| Example | `AbstractList` | `Comparable`, `Runnable` |",
"",
"> **Rule of thumb:** use an **abstract class** for an *\"is-a\"* relationship where subclasses share code; use an **interface** for a *\"can-do\"* capability that unrelated classes may all possess.",
"",
"### Achieving multiple inheritance through interfaces",
"",
"```java",
"interface Engine { void start(); }",
"interface Music  { void play(); }",
"interface GPS    { void navigate(); }",
"",
"class SmartCar implements Engine, Music, GPS {",
"    public void start()    { }",
"    public void play()     { }",
"    public void navigate() { }",
"}",
"```",
"",
"There is no diamond problem because interfaces contribute **no implementation and no state** — only a contract. (Java 8 default methods reintroduce a mild version of the problem, which Java resolves by requiring the class to override explicitly.)",
"",
"{{PYQ:abstract-classes-interfaces}}",
