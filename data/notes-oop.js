"## 5.6 Exception handling",
"",
"An **exception** is an event that disrupts the normal flow of a program at run time. Java represents it as an **object**, thrown where the error occurs and caught wherever the programmer chooses to deal with it.",
"",
"### The hierarchy",
"",
"```",
"                       Throwable",
"                      ╱         ╲",
"                 Error           Exception",
"          (unrecoverable)       ╱          ╲",
"      StackOverflowError   RuntimeException   IOException",
"      OutOfMemoryError    (UNCHECKED)         SQLException",
"                            │                 FileNotFoundException",
"                            ├─ ArithmeticException      (CHECKED)",
"                            ├─ NullPointerException",
"                            ├─ ArrayIndexOutOfBoundsException",
"                            ├─ ClassCastException",
"                            └─ NumberFormatException",
"```",
"",
"### Checked versus unchecked",
"",
"| Point | **Checked** | **Unchecked** |",
"|---|---|---|",
"| Also called | Compile-time exceptions | Run-time exceptions |",
"| Checked by compiler | **Yes** — must be handled or declared | No |",
"| Superclass | `Exception` (not `RuntimeException`) | `RuntimeException` / `Error` |",
"| Cause | External conditions beyond the program's control | **Programming mistakes** |",
"| If unhandled | **Compile error** | Compiles; crashes at run time |",
"| Examples | `IOException`, `SQLException`, `FileNotFoundException`, `ClassNotFoundException`, `InterruptedException` | `ArithmeticException`, `NullPointerException`, `ArrayIndexOutOfBoundsException`, `NumberFormatException` |",
"| Recovery | Usually possible and expected | Should be **prevented**, not caught |",
"",
"### The five keywords",
"",
"| Keyword | Purpose |",
"|---|---|",
"| `try` | Encloses code that may throw |",
"| `catch` | Handles a particular exception type |",
"| `finally` | **Always** executes — used for cleanup |",
"| `throw` | **Explicitly throws** one exception object |",
"| `throws` | **Declares** that a method may propagate exceptions |",
"",
"### `throw` versus `throws`",
"",
"| | `throw` | `throws` |",
"|---|---|---|",
"| Used to | Actually throw an exception | Declare exceptions in the signature |",
"| Placed | Inside the method body | After the parameter list |",
"| Followed by | An **instance** | One or more **class names** |",
"| Number | One at a time | Several, comma-separated |",
"| Example | `throw new IOException(\"failed\");` | `void read() throws IOException` |",
"",
"### Complete example",
"",
"```java",
"public class ExceptionDemo {",
"    static void checkAge(int age) throws Exception {      // 'throws' declares",
"        if (age < 18) throw new Exception(\"Not eligible\"); // 'throw' throws",
"        System.out.println(\"Eligible to vote\");",
"    }",
"",
"    public static void main(String[] args) {",
"        int[] arr = { 10, 20, 30 };",
"        try {",
"            System.out.println(arr[1] / 0);          // ArithmeticException",
"        }",
"        catch (ArithmeticException e) {              // MOST SPECIFIC first",
"            System.out.println(\"Arithmetic: \" + e.getMessage());",
"        }",
"        catch (Exception e) {                        // most general LAST",
"            System.out.println(\"General: \" + e);",
"        }",
"        finally {",
"            System.out.println(\"finally always runs\");",
"        }",
"        System.out.println(\"Program continues normally\");",
"    }",
"}",
"```",
"",
"> **Rule:** catch blocks must go from **most specific to most general**. Writing `catch (Exception e)` before `catch (ArithmeticException e)` is a **compile error**, because the second becomes unreachable.",
"",
"### Advantages of exception handling",
"",
"1. **Separates error-handling code from normal logic** — the algorithm stays readable",
"2. **The program does not crash** — execution continues after the handler",
"3. **Errors propagate up the call stack** to a method that can deal with them, instead of returning meaningless error codes",
"4. **Errors are grouped and typed** — catch broadly or narrowly as needed",
"5. **Meaningful diagnostics** — message, type and full stack trace",
"6. **Guaranteed cleanup** through `finally` and try-with-resources",
"7. **Enforced handling** of checked exceptions — the compiler will not let you silently ignore an I/O failure",
"",
"### User-defined exceptions",
"",
"```java",
"class NoMatchException extends Exception {",
"    public NoMatchException(String message) { super(message); }",
"}",
"",
"static void checkCountry(String input) throws NoMatchException {",
"    if (!input.equals(\"India\"))",
"        throw new NoMatchException(\"No Match: \\\"\" + input + \"\\\" is not India\");",
"    System.out.println(\"Match found\");",
"}",
"```",
"Extend `Exception` for a **checked** custom exception, `RuntimeException` for an **unchecked** one.",
"",
"### Exception propagation",
"",
"If a method does not catch an exception it is **passed up the call stack** to its caller, and so on. If it reaches `main` uncaught, the JVM's default handler prints the stack trace and terminates the program.",
"",
"```java",
"void m() { int x = 10 / 0; }          // originates here",
"void n() { m(); }                     // does not catch — propagates",
"void p() { try { n(); } catch (ArithmeticException e) { … } }   // caught here",
"```",
"",
"**Rule:** *unchecked* exceptions propagate automatically; *checked* exceptions propagate only if every method in the chain declares them with `throws`.",
"",
