"# Module 4 — Polymorphism",
"",
"---",
"",
"## 4.1 What polymorphism is",
"",
"**Polymorphism** (Greek: *poly* = many, *morph* = form) is the ability of one interface to take **many forms** — the same method name behaving differently depending on the context or on the actual object.",
"",
"### Its importance in OOP",
"",
"1. **One interface, many implementations** — one line of calling code works for every subtype",
"2. **Extensibility** — a new subclass can be added and used by existing code **without modifying that code** (the Open/Closed Principle)",
"3. **Reduced coupling** — code depends on an abstraction, not on concrete classes",
"4. **Cleaner code** — no long `if/else` or `switch` chains on type",
"5. **Enables frameworks and design patterns** — Strategy, Factory and Template Method all rest on it",
"",
"### How it promotes extensibility",
"",
"```java",
"// Written once, never touched again:",
"void renderAll(Shape[] shapes) {",
"    for (Shape s : shapes) s.draw();",
"}",
"",
"// Six months later:",
"class Hexagon extends Shape { @Override void draw() { … } }",
"```",
"`renderAll` handles `Hexagon` correctly **without a single change**. Without polymorphism it would need a new `if` branch every time, and every such edit risks breaking working code.",
"",
"---",
"",
"## 4.2 Compile-time polymorphism — method overloading",
"",
"Several methods share a **name** but differ in their **parameter list** — number, type or order. The compiler selects the right one from the arguments.",
"",
"```java",
"class Calculator {",
"    int    add(int a, int b)        { return a + b; }",
"    int    add(int a, int b, int c) { return a + b + c; }   // different count",
"    double add(double a, double b)  { return a + b; }       // different type",
"    String add(String a, String b)  { return a + b; }",
"}",
"c.add(2, 3);            // → 5",
"c.add(2, 3, 4);         // → 9",
"c.add(2.5, 3.5);        // → 6.0",
"c.add(\"Ja\", \"va\");      // → Java",
"```",
"",
"> **The return type alone cannot distinguish overloaded methods** — the compiler would have no way to choose. This is a standard one-mark point.",
"",
"Constructors can be overloaded in exactly the same way.",
"",
"---",
"",
"## 4.3 Run-time polymorphism — method overriding",
"",
"A subclass provides its **own implementation** of a method already defined in the superclass, with the **same signature**. The JVM decides which version to run from the **actual object**, not the reference type.",
"",
"```java",
"class Animal { void sound() { System.out.println(\"Some sound\"); } }",
"class Dog extends Animal { @Override void sound() { System.out.println(\"Woof\"); } }",
"class Cat extends Animal { @Override void sound() { System.out.println(\"Meow\"); } }",
"",
"Animal[] zoo = { new Dog(), new Cat(), new Animal() };",
"for (Animal x : zoo) x.sound();   // Woof / Meow / Some sound",
"```",
"",
"The reference type is `Animal` in every case, yet three different methods run — this is **dynamic method dispatch**.",
"",
"### How the JVM handles overriding at run time",
"",
"1. At **compile time**, the compiler checks only that the method exists in the **reference** type (`Animal.sound()`). If it does not, compilation fails.",
"2. Each class has a **method table (vtable)** built by the JVM, holding pointers to its actual implementations. An overriding method **replaces** the parent's entry.",
"3. At **run time**, the JVM reads the object's header, finds its class, looks up the method in that class's table and invokes it — this is **late binding**, implemented by the `invokevirtual` bytecode.",
"4. The JIT compiler often optimises this away when only one implementation is loaded (monomorphic inline caching).",
"",
"### Rules for overriding",
"",
"- Same name, same parameter list, same or **covariant** return type",
"- Access modifier **cannot be more restrictive** than the parent's",
"- Cannot throw **broader checked exceptions** than the parent's",
"- `private`, `static` and `final` methods **cannot be overridden**",
"- Use `@Override` — it makes the compiler catch a mistyped signature",
"",
"---",
"",
"## 4.4 Overloading versus overriding — the central comparison",
"",
"| Point | **Overloading** | **Overriding** |",
"|---|---|---|",
"| Also called | Compile-time / static polymorphism | Run-time / dynamic polymorphism |",
"| Where | Within the **same class** | Across **superclass and subclass** |",
"| Parameters | **Must differ** | **Must be identical** |",
"| Return type | May differ | Same or covariant |",
"| Binding | **Early** (compile time) | **Late** (run time) |",
"| Inheritance needed | No | **Yes** |",
"| `private`/`static`/`final` | Can be overloaded | **Cannot** be overridden |",
"| Access modifier | Free | Cannot be more restrictive |",
"| Exceptions | Free | No broader checked exceptions |",
"| Performance | Faster | Slight run-time lookup cost |",
"| Purpose | Convenience — one name for related operations | Specialisation — redefine inherited behaviour |",
"",
"### Using both in one program",
"",
"They are independent mechanisms and commonly appear together.",
"",
"```java",
"class Shape {",
"    void draw()         { System.out.println(\"Drawing a shape\"); }",
"    void draw(String c) { System.out.println(\"Drawing a shape in \" + c); }  // overload",
"}",
"class Circle extends Shape {",
"    @Override void draw()         { System.out.println(\"Drawing a circle\"); }        // override",
"    @Override void draw(String c) { System.out.println(\"Drawing a circle in \" + c); }",
"    void draw(int radius)         { System.out.println(\"Circle of r=\" + radius); }   // overload",
"}",
"",
"Shape s = new Circle();",
"s.draw();               // Drawing a circle        ← overriding at run time",
"s.draw(\"red\");          // Drawing a circle in red",
"// s.draw(5);           ← compile error: Shape has no draw(int)",
"((Circle) s).draw(5);   // Circle of r=5",
"```",
"",
"{{PYQ:overloading-overriding}}",
