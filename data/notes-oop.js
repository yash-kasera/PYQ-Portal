"## 3.1 Inheritance",
"",
"**Definition.** Inheritance is the mechanism by which one class acquires the fields and methods of another. The existing class is the **superclass**; the new one is the **subclass**. Java uses `extends`. It models the **\"is-a\"** relationship.",
"",
"### Purpose and uses",
"",
"1. **Code reusability** — write common behaviour once in the parent",
"2. **Method overriding** — the basis of run-time polymorphism",
"3. **Extensibility** — new subclasses without touching existing code",
"4. **Hierarchical classification** — models real taxonomies",
"5. **Maintainability** — a fix in the parent propagates to every child",
"",
"### Types of inheritance",
"",
"**1. Single** — one subclass, one superclass.",
"```",
"   A",
"   │",
"   B",
"```",
"```java",
"class Vehicle { void start() { System.out.println(\"Vehicle starting\"); } }",
"class Car extends Vehicle { void honk() { System.out.println(\"Beep!\"); } }",
"```",
"",
"**2. Multilevel** — a chain, $A \\to B \\to C$.",
"```java",
"class Animal { void eat()  { } }",
"class Dog extends Animal { void bark() { } }",
"class Puppy extends Dog  { void weep() { } }   // Puppy can call all three",
"```",
"",
"**3. Hierarchical** — several subclasses from one superclass.",
"```",
"      A",
"    ╱ │ ╲",
"   B  C  D",
"```",
"",
"**4. Multiple** — one class with two or more superclasses.",
"```",
"   A   B",
"    ╲ ╱",
"     C",
"```",
"",
"> **Java does NOT support multiple inheritance of classes**, to avoid the **diamond problem**: if both A and B define `show()`, C cannot decide which to inherit. Java achieves the same effect safely with **interfaces**, because an interface method has no body — there is nothing to conflict over.",
"",
"```java",
"interface Printable { void print(); }",
"interface Showable  { void show(); }",
"class Document implements Printable, Showable {   // 'multiple inheritance' in Java",
"    public void print() { System.out.println(\"printing\"); }",
"    public void show()  { System.out.println(\"showing\"); }",
"}",
"```",
