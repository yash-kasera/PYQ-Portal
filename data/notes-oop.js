"## 4.5 Early binding versus late binding",
"",
"**Binding** is the association of a method call with the method body.",
"",
"| | **Early (static) binding** | **Late (dynamic) binding** |",
"|---|---|---|",
"| Resolved at | **Compile time** | **Run time** |",
"| Decided by | The **reference** type | The **object** type |",
"| Applies to | `static`, `private`, `final` methods; overloaded methods; **all variables** | Overridden instance methods |",
"| Speed | Faster | Slightly slower |",
"| Flexibility | Low | **High** |",
"| Also called | Static binding | Dynamic binding |",
"",
"```java",
"class A { static void s() { System.out.println(\"A.s\"); }",
"          void i()        { System.out.println(\"A.i\"); } }",
"class B extends A { static void s() { System.out.println(\"B.s\"); }",
"                    void i()        { System.out.println(\"B.i\"); } }",
"",
"A ref = new B();",
"ref.s();     // A.s  ← EARLY binding: chosen from the REFERENCE type",
"ref.i();     // B.i  ← LATE  binding: chosen from the OBJECT type",
"```",
"",
"> **This example is worth memorising** — it demonstrates both bindings in four lines and answers several exam questions at once. Note also that **variables are always early-bound**, so `ref.x` uses `A`'s field even when the object is a `B`.",
