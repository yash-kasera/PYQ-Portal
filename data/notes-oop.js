"**5. Hybrid** — a combination; achievable in Java only through interfaces.",
"",
"### Access specifiers in inheritance",
"",
"| Member in superclass | Subclass, same package | Subclass, different package |",
"|---|---|---|",
"| `private` | ✘ (inherited but inaccessible) | ✘ |",
"| default | ✔ | ✘ |",
"| `protected` | ✔ | ✔ |",
"| `public` | ✔ | ✔ |",
"",
"### The `super` keyword",
"",
"| Use | Meaning |",
"|---|---|",
"| `super.field` | The parent's field, when the child hides it |",
"| `super.method()` | The parent's version of an overridden method |",
