"## 5.5 Synchronization",
"",
"### The problem — race condition",
"",
"```java",
"class Counter {",
"    private int count = 0;",
"    public void increment() { count++; }   // NOT atomic: read, add, write",
"}",
"// Two threads each incrementing 10,000 times often ends below 20,000.",
"```",
"",
"### The solution",
"",
"`synchronized` requires a thread to hold the object's **monitor lock**; only one thread can hold it at a time.",
"",
"```java",
"public synchronized void increment() { count++; }    // synchronized method",
"",
"public void increment2() {",
"    synchronized (this) { count++; }                 // synchronized block — finer grained",
"}",
"```",
"",
"**When to use it:** whenever two or more threads access **mutable shared state** and at least one writes. If the data is immutable or confined to one thread, no synchronization is needed.",
"",
"**Costs:** locking is slower, and careless locking causes **deadlock** — two threads each holding the lock the other needs.",
"",
"### Inter-thread communication",
"",
"Three `final` methods of `Object`, callable only inside a synchronized context:",
"",
"| Method | Effect |",
"|---|---|",
"| `wait()` | **Releases the lock** and suspends the thread until notified |",
"| `notify()` | Wakes **one** waiting thread |",
"| `notifyAll()` | Wakes **all** waiting threads |",
"",
"```java",
"class Buffer {",
"    private int data;",
"    private boolean empty = true;",
"",
"    public synchronized void produce(int value) throws InterruptedException {",
"        while (!empty) wait();            // wait until the consumer takes it",
"        data = value;  empty = false;",
"        notifyAll();",
"    }",
"    public synchronized int consume() throws InterruptedException {",
"        while (empty) wait();             // wait until something is produced",
"        empty = true;",
"        notifyAll();",
"        return data;",
"    }",
"}",
"```",
"",
"> Always call `wait()` inside a **`while`** loop, never an `if` — a thread can wake spuriously.",
"",
"### `sleep()` versus `wait()`",
"",
"| | `sleep()` | `wait()` |",
"|---|---|---|",
"| Defined in | `Thread` | `Object` |",
"| **Releases the lock** | **No** | **Yes** |",
"| Wakes when | Time expires | `notify()` / `notifyAll()` / timeout |",
"| Must be in synchronized block | No | **Yes** |",
"",
"### Important Thread methods",
"",
"| Method | Purpose |",
"|---|---|",
"| `start()` | Creates a new thread and calls `run()` on it |",
"| `sleep(ms)` | Pauses the current thread; **keeps** its locks |",
"| `join()` | Waits for another thread to finish |",
"| `interrupt()` | Sets the interrupt flag; a sleeping thread throws `InterruptedException` |",
"| `isAlive()` | Started and not yet terminated? |",
"| `yield()` | Hints willingness to give up the CPU |",
"| `setDaemon(true)` | Background thread that does not prevent JVM exit |",
"",
