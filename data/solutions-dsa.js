"",
"---",
"",
"#### 1. Simple (linear) queue",
"",
"```c",
"#include <stdio.h>",
"#define MAX 5",
"",
"int queue[MAX], front = -1, rear = -1;",
"",
"void enqueue(int x) {",
"    if (rear == MAX - 1) { printf(\"Queue Overflow\\n\"); return; }",
"    if (front == -1) front = 0;      /* first insertion */",
"    queue[++rear] = x;",
