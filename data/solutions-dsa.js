"#### Threaded binary tree",
"",
"**The motivation.** In an ordinary binary tree with $n$ nodes there are $2n$ pointer fields, of which $n+1$ are `NULL` — more than half are wasted. A **threaded binary tree** replaces these NULL pointers with **threads**: pointers to the in-order predecessor or successor.",
