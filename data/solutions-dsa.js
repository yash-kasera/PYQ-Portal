"```",
"1. Scan left to right.",
"2. Operand → push its value.",
"3. Operator → pop op1 (top) and op2; compute  op2 (operator) op1 ; push the result.",
"4. The value left on the stack is the answer.",
"```",
"",
"#### Worked example — evaluate $4,5,2,\\char`\\^,7,5,-,*,+,4,6,2,/,+,2,3,*,-,-$",
"",
"| Token | Action | Stack |",
"|---|---|---|",
"| 4 | push | 4 |",
"| 5 | push | 4 5 |",
"| 2 | push | 4 5 2 |",
"| ^ | $5^2 = 25$ | 4 25 |",
"| 7 | push | 4 25 7 |",
"| 5 | push | 4 25 7 5 |",
"| − | $7-5 = 2$ | 4 25 2 |",
"| * | $25 \\times 2 = 50$ | 4 50 |",
"| + | $4 + 50 = 54$ | 54 |",
"| 4 | push | 54 4 |",
"| 6 | push | 54 4 6 |",
"| 2 | push | 54 4 6 2 |",
"| / | $6/2 = 3$ | 54 4 3 |",
"| + | $4 + 3 = 7$ | 54 7 |",
"| 2 | push | 54 7 2 |",
"| 3 | push | 54 7 2 3 |",
"| * | $2 \\times 3 = 6$ | 54 7 6 |",
"| − | $7 - 6 = 1$ | 54 1 |",
"| − | $54 - 1 = 53$ | **53** |",
"",
"$$\\boxed{\\text{Result} = 53}$$",
"",
"#### Evaluating a prefix expression",
"",
"Scan **right to left**; on an operator pop op1 then op2 and compute `op1 (operator) op2`.",
"",
"**Example:** $+\\,+\\,8\\,/\\,*\\,2\\,3\\,1\\,/\\,*\\,4\\,1\\,2$",
"",
"Working right to left: $*\\,4\\,1 = 4$; $/\\,4\\,2 = 2$; $*\\,2\\,3 = 6$; $/\\,6\\,1 = 6$; $+\\,8\\,6 = 14$; $+\\,14\\,2 = 16$.",
"$$\\boxed{= 16}$$",
"",
"#### Implementation",
"",
"```c",
"int evaluatePostfix(char *exp) {",
"    int stack[MAX], top = -1;",
"    for (int i = 0; exp[i]; i++) {",
"        if (isdigit(exp[i]))",
"            stack[++top] = exp[i] - '0';",
"        else if (exp[i] != ' ') {",
"            int op1 = stack[top--];",
"            int op2 = stack[top--];",
"            switch (exp[i]) {",
"                case '+': stack[++top] = op2 + op1; break;",
"                case '-': stack[++top] = op2 - op1; break;",
"                case '*': stack[++top] = op2 * op1; break;",
"                case '/': stack[++top] = op2 / op1; break;",
"                case '^': { int r = 1;",
"                            for (int k = 0; k < op1; k++) r *= op2;",
"                            stack[++top] = r; } break;",
"            }",
"        }",
"    }",
"    return stack[top];",
"}",
"```"
