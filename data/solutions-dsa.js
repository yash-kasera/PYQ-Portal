"### Stack",
"",
"#### Definition",
"",
"A **stack** is a linear data structure in which insertion and deletion happen at only **one end**, called the **top**. It follows the **LIFO** (Last In, First Out) principle — the element inserted most recently is the one removed first.",
"",
"#### Stack ADT — the operations",
"",
"| Operation | Description | Complexity |",
"|---|---|---|",
"| `push(x)` | Insert `x` at the top | $O(1)$ |",
"| `pop()` | Remove and return the top element | $O(1)$ |",
"| `peek()` / `top()` | Return the top without removing it | $O(1)$ |",
"| `isEmpty()` | Is the stack empty? | $O(1)$ |",
"| `isFull()` | Is the stack full? (array version) | $O(1)$ |",
"| `display()` | Print all elements | $O(n)$ |",
"",
"Two error conditions: **overflow** (push on a full stack) and **underflow** (pop on an empty stack).",
"",
"---",
"",
"#### Implementation using an array",
"",
"```c",
"#include <stdio.h>",
"#define MAX 100",
"",
"int stack[MAX];",
"int top = -1;               /* -1 means empty */",
"",
"int isEmpty() { return top == -1; }",
"int isFull()  { return top == MAX - 1; }",
"",
"void push(int x) {",
"    if (isFull()) { printf(\"Stack Overflow\\n\"); return; }",
"    stack[++top] = x;",
"    printf(\"%d pushed\\n\", x);",
"}",
"",
"int pop() {",
"    if (isEmpty()) { printf(\"Stack Underflow\\n\"); return -1; }",
"    return stack[top--];",
"}",
"",
"int peek() {",
"    if (isEmpty()) { printf(\"Stack is empty\\n\"); return -1; }",
"    return stack[top];",
"}",
"",
"void display() {",
"    if (isEmpty()) { printf(\"Empty\\n\"); return; }",
"    printf(\"Stack (top to bottom): \");",
"    for (int i = top; i >= 0; i--) printf(\"%d \", stack[i]);",
"    printf(\"\\n\");",
"}",
"",
"int main() {",
"    push(10); push(20); push(30);",
"    display();                       /* 30 20 10 */",
"    printf(\"Popped: %d\\n\", pop());   /* 30 */",
"    printf(\"Top is: %d\\n\", peek());  /* 20 */",
"    return 0;",
"}",
"```",
"",
"#### Implementation using a linked list (pointers)",
"",
"```c",
"#include <stdio.h>",
"#include <stdlib.h>",
"",
"struct Node { int data; struct Node *next; };",
"struct Node *top = NULL;",
"",
"void push(int x) {",
"    struct Node *n = (struct Node *) malloc(sizeof(struct Node));",
"    if (!n) { printf(\"Heap overflow\\n\"); return; }",
"    n->data = x;",
"    n->next = top;          /* new node points to the old top */",
"    top = n;                /* new node becomes the top       */",
