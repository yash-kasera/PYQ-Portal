"void enqueue(int x) {",
"    if (isFull()) { printf(\"Queue is Full\\n\"); return; }",
"    if (front == -1) front = 0;",
"    rear = (rear + 1) % MAX;         /* wrap around */",
"    cq[rear] = x;",
