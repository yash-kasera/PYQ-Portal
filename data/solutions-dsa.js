"### AVL tree",
"",
"#### Definition",
"",
"An **AVL tree** (Adelson-Velsky and Landis, 1962) is a **self-balancing binary search tree** in which, for every node,",
"",
"$$\\text{Balance Factor} = \\text{height(left subtree)} - \\text{height(right subtree)} \\;\\in\\; \\{-1, 0, +1\\}$$",
"",
"If any node's balance factor goes outside this range after an insertion or deletion, the tree is rebalanced by **rotations**. This keeps the height at $O(\\log n)$, so search, insert and delete are all guaranteed $O(\\log n)$ — unlike a plain BST which can degenerate to $O(n)$.",
"",
"---",
"",
"#### The four rotations",
"",
"**1. LL rotation (Left-Left) — single right rotation**",
"Occurs when a node is inserted in the **left subtree of the left child**.",
"```",
"      z (BF=+2)                 y",
"     ╱                        ╱   ╲",
"    y            ──▶         x     z",
"   ╱",
"  x",
"```",
"",
"**2. RR rotation (Right-Right) — single left rotation**",
"Inserted in the **right subtree of the right child**.",
"```",
"  z (BF=−2)                     y",
"    ╲                         ╱   ╲",
"     y          ──▶          z     x",
"      ╲",
"       x",
"```",
"",
"**3. LR rotation (Left-Right) — double: left then right**",
"Inserted in the **right subtree of the left child**.",
"```",
"      z              z             x",
"     ╱              ╱            ╱   ╲",
"    y      ──▶     x     ──▶    y     z",
"     ╲            ╱",
"      x          y",
"```",
"",
"**4. RL rotation (Right-Left) — double: right then left**",
"Inserted in the **left subtree of the right child**.",
"```",
"  z              z                 x",
"    ╲              ╲             ╱   ╲",
"     y    ──▶       x    ──▶    z     y",
"    ╱                 ╲",
"   x                   y",
"```",
"",
"| Imbalance | Insert position | Rotation | Rotations needed |",
"|---|---|---|---|",
"| LL | left of left | Right | 1 |",
"| RR | right of right | Left | 1 |",
"| LR | right of left | Left then Right | 2 |",
"| RL | left of right | Right then Left | 2 |",
"",
"---",
"",
"#### Worked example — insert 48, 25, 10, 5, 7, 3, 28, 20, 8, 16",
"",
"| Insert | Effect | Action |",
"|---|---|---|",
"| **48** | Root | — |",
"| **25** | Left of 48 | Balanced |",
"| **10** | Left of 25 → 48 has BF +2, LL case | **Right rotation at 48** → root becomes 25, children 10 and 48 |",
"| **5** | Left of 10 | Balanced |",
"| **7** | Right of 5 → 10 has BF +2, LR case | **LR at 10** → 7 becomes parent of 5 and 10 |",
"| **3** | Left of 5 | Balanced |",
"| **28** | Left of 48 | Balanced |",
"| **20** | Left of 25's right… | Balanced |",
