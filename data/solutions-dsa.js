"| Type | What replaces the NULLs |",
"|---|---|",
"| **Single (right) threaded** | A NULL right pointer → in-order successor |",
"| **Single (left) threaded** | A NULL left pointer → in-order predecessor |",
"| **Double (fully) threaded** | Both |",
